"""roll_offsets.json -> ../RollOffsets.Data.cs"""
import json, sys
T = json.load(open(sys.argv[1])); out = sys.argv[2]
tau = T['tau']
L = ['// <auto-generated> 由 tools/roll_offset_templates.py + gen_roll_cs.py 从真人 replay 统计生成, 不要手改 </auto-generated>',
     'namespace BotPlay\n{\n    public static partial class RollOffsets\n    {',
     f'        public const float TauStart = {tau[0]:.2f}f;', f'        public const float TauStep = {tau[1]-tau[0]:.2f}f;',
     '        // 切到方块前后, 真人手腕扭转相对 "只看指向" 模型的偏移 (度), 已乘上一致性 R (越不一致的方向越保守)',
     '        // 下标: [手 0=左 1=右][切割方向 0..7 箭头, 8 点块][τ]',
     '        static readonly float[][][] Data =\n        {']
for hand in ('L', 'R'):
    L.append('            new float[][]\n            {')
    for cd in range(9):
        g = [x for x in T['groups'] if x['hand'] == hand and x['dir'] == cd]
        vals = [o * r for o, r in zip(g[0]['offset'], g[0]['R'])] if g else [0.0] * len(tau)
        L.append('                new float[] { ' + ', '.join(f'{v:.1f}f' for v in vals) + ' },')
    L.append('            },')
L.append('        };\n    }\n}')
open(out, 'w', encoding='utf-8-sig', newline='\r\n').write('\n'.join(L) + '\n')
print('ok', len(tau))
