import json, sys
T=json.load(open(sys.argv[1])); out=sys.argv[2]
L=['// <auto-generated> 由 tools/swing_templates.py + gen_cs.py 从真人 replay 统计生成, 不要手改 </auto-generated>',
   'namespace BotPlay\n{\n    public static partial class SwingTemplates\n    {']
tau=T['tau']
L+= [f'        public const float TauStart = {tau[0]:.2f}f;', f'        public const float TauStep = {tau[1]-tau[0]:.2f}f;', f'        public const int TauCount = {len(tau)};',
     '        // rel: 和上一刀挥动方向的夹角 0=0° 1=45° 2=90° 3=135° 4=180°(来回挥);  dir: 0=down 1=up 2=side 3=any;  gap: 和上一刀的时间间隔区间(秒)',
     '        // alpha: 沿挥动方向的角度(度, 负=还在后方);  beta: 偏离挥动平面的侧向角度(度, 右手为准, 左手取反)',
     '        static readonly Template[] All =\n        {']
dm={'down':0,'up':1,'side':2,'any':3}
for g in T['groups']:
    a=', '.join(f'{x:.1f}f' for x in g['alpha']); b=', '.join(f'{x:.1f}f' for x in g['beta'])
    L.append(f'            new Template({int(g["alt"])}, {dm[g["dir"]]}, {g["gap"][0]:.2f}f, {g["gap"][1]:.2f}f, {g["n"]},\n                new float[] {{ {a} }},\n                new float[] {{ {b} }}),')
L.append('        };\n    }\n}')
open(out,'w',encoding='utf-8-sig',newline='\r\n').write('\n'.join(L)+'\n')
print(len(T['groups']),'groups')
